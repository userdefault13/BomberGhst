        public static int Width(string text, int spacing = 1)
        {
            if (string.IsNullOrEmpty(text)) return 0;
            return text.Length * (GlyphW + spacing) - spacing;
        }

        /// Draws text into a canvas with the baseline at <paramref name="y"/>.
        public static void Draw(Pix p, int x, int y, string text, Color32 color, int spacing = 1)
        {
            text = text.ToUpperInvariant();
            foreach (char ch in text)
            {
                if (!Glyphs.TryGetValue(ch, out var rows)) rows = Glyphs['?'];
                var parts = rows.Split(' ');
                for (int r = 0; r < GlyphH; r++)
                {
                    string row = parts[r];
                    for (int c = 0; c < GlyphW; c++)
                        if (row[c] == '1') p.Set(x + c, y + (GlyphH - 1 - r), color);
                }
                x += GlyphW + spacing;
            }
        }

        static readonly Dictionary<string, Sprite> Cache = new Dictionary<string, Sprite>();

        /// A sprite of the given string, outlined so it reads over any background.
        public static Sprite Text(string text, Color32 color, bool shadow = true)
        {
            string key = text + "|" + color.r + "," + color.g + "," + color.b + "|" + shadow;
            if (Cache.TryGetValue(key, out var s) && s != null) return s;

            int pad = shadow ? 1 : 0;
            var p = new Pix(Width(text) + pad * 2, GlyphH + pad * 2);
            Draw(p, pad, pad, text, color);
            if (shadow) p.Outline(Pal.Ink);
            s = p.ToSprite(0.5f, 0.5f);
            Cache[key] = s;
            return s;
        }

        public static void ClearCache() => Cache.Clear();
